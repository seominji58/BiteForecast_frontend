/** 미리보기 칸 아래 쉬운 말 한 줄 */
export function tideWord(phase: string | null): string | null {
  if (!phase) return null;
  if (phase.includes('대조')) return '사리 무렵';
  if (phase.includes('소조')) return '조금 무렵';
  if (phase.includes('중조')) return '중간 물때';
  return null;
}
